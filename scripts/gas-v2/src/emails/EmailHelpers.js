/**
 * Pieces more than one V2 email template needs.
 *
 * This file was `Templates.js` until the renderers moved into one file each; it keeps the
 * doctrine that governs all of them, plus the helpers they share. It renders no message on
 * its own. **Do not add a second copy of anything here to a renderer file.** V1's templates
 * existed in two hand-synced copies and the two drifted silently until a parity test caught
 * it; one copy of each piece, called across files, is the whole point of the arrangement.
 *
 * Apps Script concatenates every pushed file into ONE global scope, so a renderer in a
 * sibling file calls `firstNameOf` by bare name with no import, and nothing here may read a
 * value from another file at load time.
 *
 * Every renderer returns { ok, subject, htmlBody, textBody }, and its plain-text part is
 * WRITTEN as a specification rather than generated by stripping tags, because the design
 * treats it as the real second half of a multipart alternative: a partner has to be able to
 * work a whole digest from the text part alone.
 *
 * TWO RULES RUN THROUGH EVERY TEMPLATE IN THIS FOLDER.
 *
 * 1. Human labels, never wire tokens. `property_owner_operator` is a storage value.
 *    See Labels.js.
 *
 * 2. Missing optional values DISAPPEAR rather than rendering empty. A row that must
 *    exist but has no verified value is omitted, never shown blank and never filled
 *    with an invented placeholder. The single exception is the digest, where "Not
 *    provided" is itself information: an empty Email row is the signal that no
 *    acknowledgement could be sent.
 *
 * Nothing in this folder contains a tracking pixel, an open-tracking image, a click-wrapped
 * link, marketing enrollment, nurture language, or a preference centre. These are
 * transactional messages.
 */

