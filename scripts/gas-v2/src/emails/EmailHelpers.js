function firstNameOf(fullName) {
  var n = normalizeWhitespace(fullName);
  if (n === '') return '';
  return n.split(' ')[0];
}

/** Adds a row only when the value is present. Optional values disappear cleanly. */
function pushRow(rows, key, value) {
  var v = normalizeWhitespace(value);
  if (v !== '') rows.push([key, v]);
}

/**
 * Human date and time with the zone NAMED IN WORDS.
 *
 * The zone is never omitted. A time without a zone in an email that crosses time zones
 * is an appointment somebody will miss, so if the offset cannot be resolved the ISO
 * instant is printed instead of a friendly-looking but ambiguous local time.
 */
function formatInstant(iso, config) {
  var d = parseIso(iso);
  if (!d) return String(iso || '');
  var resolver = (config && config.offsetResolver) || null;
  if (typeof resolver !== 'function') return d.toISOString();

  var local = new Date(d.getTime() + resolver(d) * 60000);
  var months = ['January', 'February', 'March', 'April', 'May', 'June',
    'July', 'August', 'September', 'October', 'November', 'December'];
  var days = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];

  var hour24 = local.getUTCHours();
  var suffix = hour24 >= 12 ? 'PM' : 'AM';
  var hour12 = hour24 % 12 === 0 ? 12 : hour24 % 12;
  var minutes = local.getUTCMinutes();
  var mm = minutes < 10 ? '0' + minutes : String(minutes);

  return days[local.getUTCDay()] + ', ' + months[local.getUTCMonth()] + ' ' + local.getUTCDate() +
    ', ' + local.getUTCFullYear() + ', ' + hour12 + ':' + mm + ' ' + suffix + ' Central Time';
}

